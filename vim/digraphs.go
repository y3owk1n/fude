// digraphOf returns the first of the digraphs that type r, or false.
func digraphOf(r rune) (string, bool) {
	for _, d := range slices.Sorted(maps.Keys(digraphs)) {
		if digraphs[d] == r {
			return d, true
		}
	}
	return "", false
}

